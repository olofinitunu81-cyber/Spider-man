# Writes js/scene/heromodel.js: the baked bust (zlib + base64) and its masks as data URIs.
# Usage: python3 tools/hero/pack.py <out folder> js/scene/heromodel.js
import sys, json, base64, zlib, os
src, dst = sys.argv[1], sys.argv[2]
m = json.load(open(os.path.join(src, 'model.json')))
mesh = base64.b64encode(zlib.compress(base64.b64decode(m['b64']), 9)).decode()
def uri(name, kind):
    return 'data:image/' + kind + ';base64,' + base64.b64encode(open(os.path.join(src, name), 'rb').read()).decode()
meta = m['meta']
meta = {k: meta[k] for k in ('V', 'T', 'bb', 'morphs', 'layout')}
meta['bb'] = [round(x, 5) for x in meta['bb']]
for k in meta['morphs']: meta['morphs'][k]['scale'] = round(meta['morphs'][k]['scale'], 6)
js = ('/* The hero: a bust baked from the 3D model supplied for this project (arms lowered for the\n'
      '   portrait, cropped at the chest, packed small). Generated by tools/hero; do not edit by hand.\n'
      '   mesh: zlib-compressed binary, laid out as meta.layout describes.\n'
      '   suit: r = main panels, g = web lines, b = chest spider. detail: cloth wrinkles. lens: lens mesh. */\n'
      'window.SMR.heroModel = {\n'
      '  meta: ' + json.dumps(meta, separators=(',', ':')) + ',\n'
      "  mesh: '" + mesh + "',\n"
      "  suit: '" + uri('suit.png', 'png') + "',\n"
      "  detail: '" + uri('detail.jpg', 'jpeg') + "',\n"
      "  lens: '" + uri('lens.jpg', 'jpeg') + "',\n"
      '};\n')
open(dst, 'w').write(js)
print(dst, len(js) // 1024, 'KB')
